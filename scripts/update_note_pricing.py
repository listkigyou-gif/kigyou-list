def update_note():
    print(f"[1/2] Đang cập nhật nội dung bài viết Note ID {NOTE_ID} với bảng giá mới nhất...")
    body_html = format_paragraphs_to_html(content_paragraphs)
    cookie_dict = get_cookies_dict()
    
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36",
        "Origin": "https://note.com",
        "Referer": "https://note.com/",
        "Content-Type": "application/json",
        "X-Requested-With": "XMLHttpRequest"
    }
    
    # 1. Lưu draft body
    save_headers = {
        **headers,
        "Referer": f"https://editor.note.com/notes/{NOTE_KEY}/edit"
    }
    save_payload = {
        "body": body_html,
        "body_length": len(body_html),
        "name": TITLE,
        "index": False,
        "is_lead_form": False
    }
    save_res = requests.post(f"https://note.com/api/v1/text_notes/draft_save?id={NOTE_ID}", headers=save_headers, cookies=cookie_dict, json=save_payload)
    print(f"Draft save status: {save_res.status_code}")
    
    # 2. Cập nhật bài đã publish
    pub_payload = {
        "name": TITLE,
        "free_body": body_html,
        "body_length": len(body_html),
        "hashtags": hashtags,
        "status": "published"
    }
    pub_res = requests.put(f"https://note.com/api/v1/text_notes/{NOTE_ID}", headers=headers, cookies=cookie_dict, json=pub_payload)
    print(f"Publish status: {pub_res.status_code}")
    if pub_res.status_code == 200:
        print("[THÀNH CÔNG] Bài viết trên Note.com đã được cập nhật bảng giá mới nhất siêu rẻ!")
        print(f"👉 Link: https://note.com/kigyoulist/n/{NOTE_KEY}")
    else:
        print(f"[LỖI] {pub_res.status_code} - {pub_res.text}")

if __name__ == "__main__":
    update_note()
